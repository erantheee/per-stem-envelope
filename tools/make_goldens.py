#!/usr/bin/env python3
"""Regenerate the small committed artifacts (run once; needs torch).

Produces:

* ``weights/contextnet_v0.2-s3.json``  — ContextNet 92-32-16-9 as plain JSON, so
  the S3/Python side needs no torch (3.6k params, 14.6 kB of f32).
* ``tests/fixtures/contextnet_golden.json`` — a few input/logit pairs computed by
  the original torch model, so CI can check the numpy/c port without torch.
* ``variants/s3/tests/golden.h`` — envelope steps produced by the reference
  ``PerStemEnvelope``, so the C port can be checked against Python.

The ``.pt`` files themselves are copied into ``weights/`` by hand (see
``weights/MANIFEST.json`` for sha256 and the licence of each).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from stemenvelope import PerStemEnvelope  # noqa: E402

CORES3 = Path.home() / "Documents/Codex/2026-10-13/cores3-noise-adapt-demo"
CONTEXTNET_PT = CORES3 / "experiments/listening-model/artifacts/model_v0.2-s3.pt"


def export_contextnet() -> None:
    import torch  # local-only dependency

    obj = torch.load(CONTEXTNET_PT, map_location="cpu", weights_only=False)
    sd = obj["state_dict"]
    payload = {
        "version": obj["metrics"].get("version", "v0.2-s3"),
        "framework": "ContextNet MLP 92-32-16-9 (Linear+ReLU), softmax over classes",
        "classes": [str(c) for c in obj["classes"]],
        "input_dim": int(sd["net.0.weight"].shape[1]),
        "hidden": [int(sd["net.0.weight"].shape[0]), int(sd["net.3.weight"].shape[0])],
        "normalisation": {"mu": [float(v) for v in obj["mu"]],
                          "sigma": [float(v) for v in obj["sigma"]]},
        "layers": [
            {"weight": sd["net.0.weight"].tolist(), "bias": sd["net.0.bias"].tolist()},
            {"weight": sd["net.3.weight"].tolist(), "bias": sd["net.3.bias"].tolist()},
            {"weight": sd["net.6.weight"].tolist(), "bias": sd["net.6.bias"].tolist()},
        ],
        "params": int(sum(v.numel() for v in sd.values())),
        "metrics": {k: v for k, v in obj["metrics"].items() if k != "classes"},
    }
    out = ROOT / "weights/contextnet_v0.2-s3.json"
    out.write_text(json.dumps(payload, indent=1), encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size} bytes)")

    # golden pairs: a seeded random walk around the training mean
    mu = np.asarray(payload["normalisation"]["mu"])
    sigma = np.asarray(payload["normalisation"]["sigma"])
    rng = np.random.default_rng(11)
    pairs = []
    net = torch.nn.Sequential(
        torch.nn.Linear(92, 32), torch.nn.ReLU(),
        torch.nn.Linear(32, 16), torch.nn.ReLU(),
        torch.nn.Linear(16, 9))
    with torch.no_grad():
        net[0].weight.copy_(torch.tensor(sd["net.0.weight"]))
        net[0].bias.copy_(torch.tensor(sd["net.0.bias"]))
        net[2].weight.copy_(torch.tensor(sd["net.3.weight"]))
        net[2].bias.copy_(torch.tensor(sd["net.3.bias"]))
        net[4].weight.copy_(torch.tensor(sd["net.6.weight"]))
        net[4].bias.copy_(torch.tensor(sd["net.6.bias"]))
        for _ in range(5):
            raw = mu + sigma * rng.standard_normal(92) * 1.5
            x = (raw - mu) / sigma
            logits = net(torch.tensor(x, dtype=torch.float32)[None, :])[0].tolist()
            pairs.append({"raw_features": [float(v) for v in raw],
                          "logits": [float(v) for v in logits]})
    golden = ROOT / "tests/fixtures/contextnet_golden.json"
    golden.parent.mkdir(parents=True, exist_ok=True)
    golden.write_text(json.dumps({"note": "computed by the original torch model",
                                  "pairs": pairs}, indent=1), encoding="utf-8")
    print(f"wrote {golden} ({len(pairs)} pairs)")


def export_envelope_golden() -> None:
    """Deterministic envelope trace for the C parity test."""
    n_stems, n_bands = 3, 6
    env = PerStemEnvelope(n_stems=n_stems, n_bands=n_bands, tau_rise_s=0.2,
                          tau_fall_s=0.4, presence_window_db=18.0,
                          silence_floor_db=-60.0, max_boost_db=3.0, max_cut_db=-9.0)
    rng = np.random.default_rng(3)
    steps = []
    for step in range(12):
        content = rng.uniform(-70.0, 10.0, size=(n_stems, n_bands))
        curve = rng.uniform(-6.0, 4.0, size=n_bands)
        active = 1 if step not in (5, 6) else 0
        gains = env.step(content, curve, dt_s=0.058, active=bool(active))
        steps.append({"stem_band_db": content.tolist(), "curve_db": curve.tolist(),
                      "dt_s": 0.058, "active": active, "gains_db": gains.tolist()})

    lines = ["/* generated by tools/make_goldens.py — do not edit by hand */",
             "#ifndef STEMENVELOPE_GOLDEN_H", "#define STEMENVELOPE_GOLDEN_H",
             "", f"#define GOLD_N_STEMS {n_stems}", f"#define GOLD_N_BANDS {n_bands}",
             f"#define GOLD_STEPS {len(steps)}", ""]
    for i, step in enumerate(steps):
        flat_in = [v for row in step["stem_band_db"] for v in row]
        flat_out = [v for row in step["gains_db"] for v in row]
        lines.append(f"static const float GOLD_IN_{i}[{len(flat_in)}] = {{"
                     + ", ".join(f"{v:.6f}f" for v in flat_in) + "};")
        lines.append(f"static const float GOLD_CURVE_{i}[{n_bands}] = {{"
                     + ", ".join(f"{v:.6f}f" for v in step["curve_db"]) + "};")
        lines.append(f"static const float GOLD_OUT_{i}[{len(flat_out)}] = {{"
                     + ", ".join(f"{v:.6f}f" for v in flat_out) + "};")
        lines.append(f"static const int GOLD_ACTIVE_{i} = {step['active']};")
        lines.append(f"static const float GOLD_DT_{i} = {step['dt_s']:.6f}f;")
        lines.append("")
    lines.append("#endif")

    header = ROOT / "variants/s3/tests/golden.h"
    header.parent.mkdir(parents=True, exist_ok=True)
    header.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {header} ({len(steps)} steps)")


if __name__ == "__main__":
    export_contextnet()
    export_envelope_golden()
